#!/usr/bin/env python3
"""Summarise the optimisation-level sweep into results/ext/opt-summary.md.

Input   results/ext/opt-*.csv   bench,level,mode,wall_s,vmpeak_kb,vmhwm_kb,vmsize_kb,checksum
Output  results/ext/opt-summary.md

The question: the paper measured at -O2 only. Does ASan's relative cost depend
on the optimisation level? One factor changes (-O0/-O1/-O2/-O3); sources,
iteration counts, ASAN_OPTIONS and the setarch -R wrapper are fixed.

Every number in the generated file is computed here from the CSV; nothing is
typed in by hand, so the summary can be regenerated and checked at any time.
The closing conclusion has fixed English wording, but every figure quoted in
it, and the supported / not supported verdict, is computed from the same data.
"""

from __future__ import annotations

import csv
import glob
import statistics
import sys
from collections import defaultdict

RAW_GLOB = "results/ext/opt-*.csv"
OUT = "results/ext/opt-summary.md"

BENCHES = ["b1_allocs", "b2_pointer", "b3_int", "b4_float", "b5_string"]
LEVELS = ["O0", "O1", "O2", "O3"]
EXCLUDED = "b1_allocs"  # allocator upper bound, excluded from the secondary mean (D15)
OTHERS = ["b2_pointer", "b3_int", "b5_string"]  # reference group for hypothesis (b)


def mean(xs: list[float]) -> float:
    return statistics.mean(xs) if xs else float("nan")


def sd(xs: list[float]) -> float:
    return statistics.stdev(xs) if len(xs) > 1 else 0.0


def load() -> tuple[list[str], dict]:
    files = sorted(glob.glob(RAW_GLOB))
    if not files:
        sys.exit(f"no data under {RAW_GLOB}; run 'make extension-opt' first")
    # (bench, level, mode) -> {"wall": [...], "chk": set()}
    data: dict = defaultdict(lambda: {"wall": [], "chk": set()})
    for path in files:
        with open(path, newline="", encoding="utf-8") as fh:
            for row in csv.DictReader(fh):
                key = (row["bench"], row["level"], row["mode"])
                data[key]["wall"].append(float(row["wall_s"]))
                data[key]["chk"].add(row["checksum"])
    return [f.replace("\\", "/") for f in files], data


def main() -> None:
    files, data = load()
    n_rows = sum(len(v["wall"]) for v in data.values())
    n_per = sorted({len(v["wall"]) for v in data.values()})

    ratio: dict[tuple[str, str], float] = {}
    for b in BENCHES:
        for lv in LEVELS:
            base, asan = data[(b, lv, "base")]["wall"], data[(b, lv, "asan")]["wall"]
            if base and asan:
                ratio[(b, lv)] = mean(asan) / mean(base)

    def level_mean(lv: str, benches: list[str]) -> float:
        return mean([ratio[(b, lv)] for b in benches if (b, lv) in ratio])

    all5 = BENCHES
    excl = [b for b in BENCHES if b != EXCLUDED]

    out = [
        "# Extension: optimisation level (-O0 / -O1 / -O2 / -O3)\n",
        "Generated by `scripts/summarize_opt.py` from "
        + ", ".join(f"`{f}`" for f in files) + ".\n",
        "One factor changed: the clang-14 optimisation level, applied identically to "
        "the baseline and the ASan build. Same sources and iteration counts as "
        "`scripts/run.sh`, every process under `setarch -R`, "
        "`ASAN_OPTIONS=malloc_context_size=0:quarantine_size_mb=0:detect_leaks=0`. "
        f"{n_rows} measurements, n = {'/'.join(map(str, n_per))} per point after one "
        "discarded warm-up. Times are mean ± sample sd; slowdown = mean ASan time / "
        "mean baseline time at the **same** level.\n",
        "> This sweep ran in one session on a different machine from the four main "
        "sessions (see D20), so its absolute times are not comparable with "
        "`results/summary.md`; only ratios within this file are compared.\n",
        "## Per workload\n",
    ]

    for b in BENCHES:
        out.append(f"### `{b}`\n")
        out.append("| level | base (s) | asan (s) | slowdown |")
        out.append("|---|---|---|---|")
        for lv in LEVELS:
            base = data[(b, lv, "base")]["wall"]
            asan = data[(b, lv, "asan")]["wall"]
            if not base or not asan:
                out.append(f"| -{lv} | – | – | – |")
                continue
            out.append(f"| -{lv} | {mean(base):.3f} ± {sd(base):.3f} | "
                       f"{mean(asan):.3f} ± {sd(asan):.3f} | {ratio[(b, lv)]:.2f}× |")
        out.append("")

    out.append("## Mean slowdown per level\n")
    out.append("| level | mean, all five | mean, excluding `b1_allocs` |")
    out.append("|---|---|---|")
    for lv in LEVELS:
        out.append(f"| -{lv} | {level_mean(lv, all5):.2f}× | {level_mean(lv, excl):.2f}× |")
    out.append("")
    out.append("`b1_allocs` is excluded from the second column for the same reason as in "
               "the main results: it is an upper bound on allocator overhead (D15).\n")

    out.append("## Checksum consistency\n")
    bad = []
    for b in BENCHES:
        sums: set[str] = set()
        for lv in LEVELS:
            for m in ("base", "asan"):
                sums |= data[(b, lv, m)]["chk"]
        if len(sums) != 1:
            bad.append((b, sorted(sums)))
    if bad:
        out.append("**Mismatch** — these workloads computed different results across "
                   "builds, so their timings are not comparable:\n")
        for b, sums in bad:
            out.append(f"- `{b}`: {', '.join(sums)}")
    else:
        out.append("Every workload produced a single checksum across all four levels "
                   "and both modes, so neither the optimisation level nor the "
                   "instrumentation changed the computed result.")
    out.append("")

    # ---- conclusion: fixed wording, computed numbers and verdicts ----------
    o0, o2 = level_mean("O0", excl), level_mean("O2", excl)
    o0_all, o2_all = level_mean("O0", all5), level_mean("O2", all5)
    f0, f1, f2 = (ratio[("b4_float", lv)] for lv in ("O0", "O1", "O2"))
    r0, r2 = level_mean("O0", OTHERS), level_mean("O2", OTHERS)
    fb0, fb2 = (mean(data[("b4_float", lv, "base")]["wall"]) for lv in ("O0", "O2"))

    # (a): "clearly smaller" = at least 10 % below the -O2 mean.
    a_holds = o0 < 0.9 * o2
    # (b) has two parts. The drop: b4 loses at least a quarter of its -O2 ratio,
    # and more than the other workloads lose. The cause: clang-14 does not run
    # the loop vectoriser at -O1, so if de-vectorisation were the main driver the
    # ratio would already have dropped by -O1 too. Both must hold.
    b_drops = f0 < 0.75 * f2 and (f2 - f0) > (r2 - r0)
    b_cause = f1 < 0.75 * f2
    b_holds = b_drops and b_cause

    out.append("## Conclusion\n")
    out.append(
        f"**Hypothesis (a): {'supported' if a_holds else 'not supported'}.** "
        f"Excluding `b1_allocs`, the mean slowdown is {o0:.2f}× at -O0 against "
        f"{o2:.2f}× at -O2 (all five: {o0_all:.2f}× vs {o2_all:.2f}×; criterion: "
        "at least 10 % lower). "
        + ("An unoptimised baseline already spends its time on loads, stores and "
           "spills, so the added shadow checks are a smaller share of the total. "
           if a_holds else
           "The relative cost does not fall clearly at -O0, so ASan's overhead is "
           "not simply diluted by a slower baseline. ")
        + "The paper's 73 % is an -O2 figure and should not be read as independent "
          "of the optimisation level.\n"
    )
    out.append(
        f"**Hypothesis (b): {'supported' if b_holds else 'not supported'}.** "
        f"`b4_float` goes from {f2:.2f}× at -O2 to {f0:.2f}× at -O0, while the mean "
        f"of `b2`/`b3`/`b5` goes from {r2:.2f}× to {r0:.2f}×, so the ratio "
        + ("does shrink markedly at -O0. " if b_drops else
           "does not shrink markedly at -O0. ")
        + f"But at -O1, where clang-14 runs no loop vectoriser, it is already {f1:.2f}× "
        + ("(also well below -O2), consistent with de-vectorisation (D16)."
           if b_cause else
           "(close to -O2), so lost vectorisation cannot be the main cause. The -O0 "
           f"drop is the dilution from (a): the -O0 baseline takes {fb0:.3f} s against "
           f"{fb2:.3f} s at -O2. The compiler's own report agrees: the hot inner loop "
           "is not vectorised in either build at -O2 (D20). D16's explanation is not "
           "confirmed; the extra cost has another source.")
        + "\n"
    )

    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print(f"wrote {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
